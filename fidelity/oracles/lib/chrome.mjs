// Chrome as the reference engine for (a) expected text and (b) the first layout reference.
// The driver (launch flags, print media, page.pdf options) is the ONE shared Chromium reference
// setup, fidelity/lib/chrome-reference.mjs. puppeteer-core only: it never downloads a browser.
// The executable is explicit (local Chrome is INDICATIVE; CI should pin a Chrome for Testing build
// via @puppeteer/browsers and pass its path through VELLORA_ORACLE_CHROME). The version actually
// used is recorded from browser.version().
import { existsSync } from "node:fs";
import { launchReferenceChrome, printInnerText, printPdf } from "../../lib/chrome-reference.mjs";
import { chromePath } from "./paths.mjs";

export async function launchChrome() {
  const executablePath = chromePath();
  if (!existsSync(executablePath)) {
    throw new Error(
      `Chrome not found at ${executablePath}; set VELLORA_ORACLE_CHROME to a Chrome/Chromium binary`,
    );
  }
  return launchReferenceChrome(executablePath);
}

/**
 * Expected text: `document.body.innerText` under print media. innerText applies CSS
 * (text-transform, display:none, block boundaries => newlines) but NOT @page margin boxes,
 * which are generated by the paginator and are therefore absent from it by definition.
 */
export function chromeInnerText(chrome, html) {
  return printInnerText(chrome, html);
}

/** Chrome's own print-to-PDF of the same HTML (layout reference + extractor control). */
export function chromePdf(chrome, html) {
  return printPdf(chrome, html);
}
