// Chrome as the reference engine for (a) expected text and (b) the first layout reference.
// puppeteer-core only: it never downloads a browser. The executable is explicit (local Chrome is
// INDICATIVE; CI should pin a Chrome for Testing build via @puppeteer/browsers and pass its path
// through VELLORA_ORACLE_CHROME). The version actually used is recorded from browser.version().
import { existsSync } from "node:fs";
import { chromePath } from "./paths.mjs";

export async function launchChrome() {
  const executablePath = chromePath();
  if (!existsSync(executablePath)) {
    throw new Error(
      `Chrome not found at ${executablePath}; set VELLORA_ORACLE_CHROME to a Chrome/Chromium binary`,
    );
  }
  const { default: puppeteer } = await import("puppeteer-core");
  const browser = await puppeteer.launch({
    executablePath,
    headless: true,
    args: ["--no-sandbox", "--disable-dev-shm-usage", "--font-render-hinting=none"],
  });
  return {
    browser,
    executablePath,
    version: await browser.version(),
    userAgent: await browser.userAgent(),
    async close() {
      await browser.close();
    },
  };
}

async function withPrintPage(chrome, html, fn) {
  const page = await chrome.browser.newPage();
  try {
    await page.emulateMediaType("print");
    await page.setContent(html, { waitUntil: "load", timeout: 120_000 });
    await page.evaluate(() => document.fonts.ready);
    return await fn(page);
  } finally {
    await page.close();
  }
}

/**
 * Expected text: `document.body.innerText` under print media. innerText applies CSS
 * (text-transform, display:none, block boundaries => newlines) but NOT @page margin boxes,
 * which are generated by the paginator and are therefore absent from it by definition.
 */
export function chromeInnerText(chrome, html) {
  return withPrintPage(chrome, html, (page) => page.evaluate(() => document.body.innerText));
}

/** Chrome's own print-to-PDF of the same HTML (layout reference + extractor control). */
export function chromePdf(chrome, html) {
  return withPrintPage(chrome, html, async (page) => {
    const pdf = await page.pdf({ format: "A4", preferCSSPageSize: true, printBackground: true });
    return new Uint8Array(pdf);
  });
}
